// The floor reshaped to his taste model (Wave 2, W2.10). Krish, 2026-10-29: "I would much rather the engine know what
// kind of thing doesn't fly with me, rather than implement incredibly specific rules everywhere which came from
// feedback on one piece of content for one specific reason." So every standard the engine drafted from his rejections
// sits in one of three layers:
//
//   floor     one of the eight nevers he confirmed on 2026-10-29 ("Yes, that's the floor"), the only things that may
//             block on taste, and only once he has approved the standard;
//   aim       what great looks like (the brand book, minimal random components, good motion, animation and visuals,
//             simple, classy, on brand): guides the work, never blocks;
//   example   everything else: a dated example of the kind of thing that does not fly, never a new rule.
//
// The sort is code, never a model (AGENTS.md rule 3: what the engine reads is labelled as its reading): fixed rules on
// the standard's own theme, layer and words, versioned by SORT_REV. It is a proposal he confirms in one sitting with
// the floor's pull request; until then the file says each standard's layer is the engine's sort.

/** Bump when a rule below changes what a standard is sorted into. */
export const SORT_REV = 'sort-2026-10-29'

/**
 * His eight nevers, in his order, by the ids content-engine's config/reference-cuts.json gives them (floor.nevers,
 * ruling 12), with the list's words he confirmed. The floor file names them by these ids, so scripts/floor.py joins
 * each to his words there; nothing of his is copied here.
 */
export const NEVERS = [
  { id: 'his_name', listed: 'never names you or credits you as author' },
  { id: 'nothing_made_up', listed: 'nothing made up; numbers credited to their producer' },
  { id: 'every_word_in_sync', listed: 'your words never cut, changed or out of sync' },
  { id: 'empty_labels', listed: 'no AI notes, eyebrows, asterisks, take/read tags' },
  { id: 'nothing_goes_out_without_him', listed: 'nothing posted/sent/spent without your yes; never Full Time or Heartside channels' },
  { id: 'real_marks_with_rights', listed: 'real logos and images with rights, never redrawn' },
  { id: 'one_opening_one_close', listed: 'one opening, one close' },
  { id: 'no_em_dash_no_preaching', listed: 'no em dashes, no preaching' },
] as const

export type NeverId = typeof NEVERS[number]['id']
export type Layer = 'floor' | 'aim' | 'example'

export interface Sorted { layer: Layer; never: NeverId | null; rule: string }

// Each never is found by what the standard says it refuses, read in this order: the most specific first, so a standard
// about two intros is never 7 even when it mentions the logo on the second one.
