// What great looks like, by the standard's own theme or layer: the qualities he named as aims.
const AIM_THEMES = new Set(['brand', 'layout', 'decorative_motion', 'clipart_generic', 'words_on_screen', 'camera'])
const AIM_LAYERS = new Set(['graphics', 'camerawork'])

export interface Sortable { theme: string; layer: string | null; kind: string; statement: string; how_to_check: string }

/** Which layer a standard sits in, and the rule that put it there. Pure: the same standard always sorts the same way. */
export function sortStandard(s: Sortable): Sorted {
  // How sessions work with him is never taste on the work; only a never about what goes out without him is floor.
  const text = `${s.statement}\n${s.how_to_check}`
  for (const [never, re] of NEVER_RULES) {
    if (s.kind === 'workflow' && never !== 'nothing_goes_out_without_him') continue
    if (re.test(text)) return { layer: 'floor', never, rule: `never:${never}` }
  }
  if (s.kind !== 'workflow' && (AIM_THEMES.has(s.theme) || (s.layer !== null && AIM_LAYERS.has(s.layer)))) {
    return { layer: 'aim', never: null, rule: AIM_THEMES.has(s.theme) ? `aim:theme:${s.theme}` : `aim:layer:${s.layer}` }
  }
  return { layer: 'example', never: null, rule: 'example' }
}
